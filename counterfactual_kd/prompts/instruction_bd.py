def render_prompt(dataset: str, instruction: str, text: str) -> str:
    """Format the full prompt the model sees.

    Args:
        dataset:     Counterfactual-KD dataset name (sst2, hatespeech, agnews, …).
        instruction: instruction string — clean or attack-perturbed.
                     The caller decides which one (poisoned trainer/eval
                     passes the perturbed one; clean trainer passes the
                     spec's ``clean_instruction``).
        text:        the user input (one classification example).

    Returns:
        The rendered prompt, ready to be tokenized for either causal-LM
        training (with the label string appended) or evaluation
        (without — the model generates the label).
    """
    spec = DATASET_PROMPT_SPECS[dataset]
    return spec.input_glue.format(instruction=instruction, text=text)
